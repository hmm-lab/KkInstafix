"""Generate the shared Python configuration and the clean-install D1 schema."""
import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLOUDFLARE = ROOT / 'cloudflare'
KEYS = (
    'PROVIDER_REVISION', 'PROVIDERS', 'PLATFORM_EMOJI', 'TRACKING', 'PLATFORM_TRACKING',
    'INSTAGRAM_CONTENT_QUERY', 'INSTAGRAM_CONTENT_PATH', 'GENERIC_TRACKING', 'YOUTUBE_HOSTS',
    'YOUTUBE_TRACKING', 'AMAZON_TLDS', 'AMAZON_TRACKING', 'EBAY_TLDS', 'EBAY_TRACKING',
    'ALIEXPRESS_DOMAINS', 'ALIEXPRESS_TRACKING', 'LINKEDIN_TRACKING', 'PINTEREST_DOMAINS',
    'PINTEREST_TRACKING', 'APPLE_MUSIC_TRACKING', 'VIMEO_TRACKING', 'SOUNDCLOUD_TRACKING',
    'SHORT_LINK_DOMAINS',
)
RUNTIME_SCHEMA = '''
CREATE TABLE IF NOT EXISTS runtime_config (id INTEGER PRIMARY KEY CHECK(id=1), token_cipher TEXT NOT NULL, bot_id INTEGER NOT NULL, username TEXT NOT NULL, activated INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS deliveries (update_id INTEGER PRIMARY KEY, state TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS idx_deliveries_ts ON deliveries(ts);
CREATE TABLE IF NOT EXISTS recent_events (kind TEXT NOT NULL, chat_id INTEGER NOT NULL, event_key TEXT NOT NULL, ts INTEGER NOT NULL, PRIMARY KEY(kind,chat_id,event_key));
CREATE INDEX IF NOT EXISTS idx_recent_events_ts ON recent_events(ts);
CREATE TABLE IF NOT EXISTS rate_events (chat_id INTEGER NOT NULL,user_id INTEGER NOT NULL,event_id INTEGER NOT NULL,ts INTEGER NOT NULL,PRIMARY KEY(chat_id,user_id,event_id));
CREATE INDEX IF NOT EXISTS idx_rate_events_ts ON rate_events(ts);
'''


def config():
    values = {}
    for filename in ['providers.py', 'bot.py']:
        for node in ast.parse((ROOT / filename).read_text()).body:
            targets = node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
            for target in targets:
                if isinstance(target, ast.Name) and target.id in KEYS:
                    try:
                        values[target.id] = ast.literal_eval(node.value)
                    except (ValueError, TypeError) as error:
                        raise SystemExit(f'{filename}: {target.id} must be a literal') from error
    for platform, provider in values['PROVIDERS'].items():
        options = provider['options']
        aliases = provider.get('noauth_embed', {})
        if (provider['default'] not in options or any(
                alias not in options or backend not in options or backend in aliases
                for alias, backend in aliases.items())):
            raise SystemExit(f'Invalid provider default or alias for {platform}')
    return '// Generated by cloudflare/generate-config.py.\n' + ''.join(
        f'export const {key} = {json.dumps(values[key], ensure_ascii=False, default=sorted_set)};\n'
        for key in KEYS
    )


def sorted_set(value):
    if isinstance(value, set):
        return sorted(value)
    raise TypeError(f'Unsupported generated value: {type(value).__name__}')


def schema():
    module = ast.parse((ROOT / 'database.py').read_text())
    func = next(node for node in module.body if isinstance(node, ast.FunctionDef) and node.name == 'init_db')
    call = next(node for node in ast.walk(func) if isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute) and node.func.attr == 'executescript')
    return ast.literal_eval(call.args[0]) + RUNTIME_SCHEMA + ''.join(
        '\n' + migration.read_text() for migration in sorted((CLOUDFLARE / 'migrations').glob('*.sql'))
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = {'src/config.js': config(), 'schema.sql': schema()}
    for name, content in outputs.items():
        path = CLOUDFLARE / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'cloudflare/{name} is stale. Run python cloudflare/generate-config.py')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
